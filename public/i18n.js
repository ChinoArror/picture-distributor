const RAW_SELECTOR = [
  ".user-name",
  ".menu-summary strong",
  ".result-group h2",
  ".class-card h3",
  ".share-row strong",
  ".share-photo-list [title]",
  "[data-no-i18n]",
].join(",");

export function getLocale() {
  const saved = localStorage.getItem(STORAGE_KEY);
  if (SUPPORTED.has(saved)) return saved;
  return navigator.language?.toLowerCase().startsWith("zh") ? "zh" : "en";
}

export function setLocale(locale) {
  const next = SUPPORTED.has(locale) ? locale : "zh";
  localStorage.setItem(STORAGE_KEY, next);
  document.documentElement.lang = next === "zh" ? "zh-CN" : "en";
  return next;
}

export function translateText(value, locale = getLocale()) {
  if (locale !== "en" || typeof value !== "string") return value;
  const leading = value.match(/^\s*/)?.[0] || "";
  const trailing = value.match(/\s*$/)?.[0] || "";
  const core = value.slice(leading.length, value.length - trailing.length || undefined);
  const exact = EN[core];
  if (exact) return `${leading}${exact}${trailing}`;
  for (const [pattern, replace] of PATTERNS) {
    if (pattern.test(core)) return `${leading}${core.replace(pattern, replace)}${trailing}`;
  }
  return value;
}

function localizeElement(root) {
  if (!root || getLocale() !== "en") return;
  const elements = root.nodeType === Node.ELEMENT_NODE ? [root, ...root.querySelectorAll("*")] : [];
  for (const element of elements) {
    if (element.matches?.(RAW_SELECTOR) || element.closest?.(RAW_SELECTOR)) continue;
    for (const attribute of ["aria-label", "placeholder", "title"]) {
      if (!element.hasAttribute?.(attribute)) continue;
      const value = element.getAttribute(attribute);
      const translated = translateText(value, "en");
      if (translated !== value) element.setAttribute(attribute, translated);
    }
  }
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let textNode;
  while ((textNode = walker.nextNode())) {
    if (textNode.parentElement?.closest(RAW_SELECTOR)) continue;
    const translated = translateText(textNode.nodeValue, "en");
    if (translated !== textNode.nodeValue) textNode.nodeValue = translated;
  }
}

export function localize(root = document.documentElement) {
  document.documentElement.lang = getLocale() === "zh" ? "zh-CN" : "en";
  localizeElement(root);
}

export function watchLocale() {
  localize();
  const observer = new MutationObserver((records) => {
    if (getLocale() !== "en") return;
    for (const record of records) {
      if (record.type === "characterData") localizeElement(record.target.parentElement);
      else if (record.type === "attributes") localizeElement(record.target);
      else for (const node of record.addedNodes) {
        if (node.nodeType === Node.TEXT_NODE) {
          const translated = translateText(node.nodeValue, "en");
          if (translated !== node.nodeValue) node.nodeValue = translated;
        } else localizeElement(node);
      }
    }
  });
  observer.observe(document.documentElement, {
    subtree: true,
    childList: true,
    characterData: true,
    attributes: true,
    attributeFilter: ["aria-label", "placeholder", "title"],
  });
  return observer;
}

export function dateLocale() {
  return getLocale() === "en" ? "en-US" : "zh-CN";
}
